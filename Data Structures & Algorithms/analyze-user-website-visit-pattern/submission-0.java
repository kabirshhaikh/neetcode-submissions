class Solution {
    public List<String> mostVisitedPattern(String[] username, int[] timestamp, String[] website) {
        Integer[] indices = new Integer[timestamp.length];

        for (int i = 0; i < timestamp.length; i++) {
            indices[i] = i;
        }

        // Sort indices according to their timestamps
        Arrays.sort(indices, (a, b) -> Integer.compare(timestamp[a], timestamp[b]));
        // first i will generate the website list for each user:
        HashMap<String, List<String>> visit = new HashMap<>();
        for (int i : indices) {
            String name = username[i];
            String web = website[i];

            List<String> websiteList = visit.getOrDefault(name, new ArrayList<>());
            websiteList.add(web);
            visit.put(name, websiteList);
        }

        // now I will generate 3 website patterns for each user and increment patternCount when
        // generated by another user:
        HashMap<List<String>, Integer> patternCount = new HashMap<>();
        for (Map.Entry<String, List<String>> m : visit.entrySet()) {
            String user = m.getKey();
            List<String> websites = m.getValue();

            // here i create a hashset to track same pattern generated by a user, to avoid
            // accidentally incrementing count of a pattern from patternCount map.
            HashSet<List<String>> seen = new HashSet<>();
            for (int i = 0; i < websites.size(); i++) {
                for (int j = i + 1; j < websites.size(); j++) {
                    for (int k = j + 1; k < websites.size(); k++) {
                        List<String> generatedPattern =
                            Arrays.asList(websites.get(i), websites.get(j), websites.get(k));

                        if (seen.contains(generatedPattern)) {
                            // if the pattern exists then skip the currently generated pattern:
                            continue;
                        } else {
                            // add it in hashset seen:
                            seen.add(generatedPattern);

                            // then update patternCount map:
                            patternCount.put(generatedPattern,
                                patternCount.getOrDefault(generatedPattern, 0) + 1);
                        }
                    }
                }
            }
        }

        int maxCount = Integer.MIN_VALUE;
        List<String> output = new ArrayList<>();

        for (Map.Entry<List<String>, Integer> pc : patternCount.entrySet()) {
            List<String> pattern = pc.getKey();
            int count = pc.getValue();

            if (count > maxCount
                || (count == maxCount && isLexicographicallySmaller(pattern, output))) {
                maxCount = count;
                output = pattern;
            }
        }

        return output;
    }

    private boolean isLexicographicallySmaller(List<String> a, List<String> b) {
        if (b.isEmpty()) {
            return true;
        }

        for (int i = 0; i < 3; i++) {
            int comparison = a.get(i).compareTo(b.get(i));

            if (comparison < 0) {
                return true;
            }

            if (comparison > 0) {
                return false;
            }
        }

        return false;
    }
}

